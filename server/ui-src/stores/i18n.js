const savedLang = localStorage.getItem("mp-language") || "ko";

export const i18n = reactive({
	locale: savedLang,
	setLocale(lang) {
		if (messages[lang]) {
			this.locale = lang;
			localStorage.setItem("mp-language", lang);
			dayjs.locale(lang === "ko" ? "ko" : "en");
		}
	},
	t(key, params = {}) {
		const dict = messages[this.locale] || messages.en;
		let str = dict[key] || messages.en[key] || key;
		for (const [k, v] of Object.entries(params)) {
			str = str.replace(new RegExp(`\\{${k}\\}`, "g"), v);
		}
		return str;
	},
});

dayjs.locale(savedLang === "ko" ? "ko" : "en");
